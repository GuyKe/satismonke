// Host + client: machines, belts, buildings and the Hub are shared. Needs vite preview on :4173 and a local PeerServer on 127.0.0.1:9000.
import { createRequire } from 'module';
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_DIR + 'playwright');
const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--no-sandbox'] });
const URL = 'http://localhost:4173/?peerhost=127.0.0.1&peerport=9000';
const mk = async () => { const p = await b.newPage(); p.errs = []; p.on('pageerror', e => p.errs.push(String(e))); await p.goto(URL); await p.waitForFunction(() => window.__game, null, { timeout: 60000 }); return p; };
const A = await mk(), B = await mk();
await A.evaluate(() => window.__game.net.host()); await A.waitForFunction(() => window.__game.net.state === 'lobby');
const code = await A.evaluate(() => window.__game.net.code);
await B.evaluate(c => window.__game.net.join(c), code); await B.waitForFunction(() => window.__game.net.state === 'lobby', null, { timeout: 20000 });
await A.evaluate(() => window.__game.net.start()); await B.waitForFunction(() => window.__game.net.state === 'game', null, { timeout: 20000 }); await A.waitForTimeout(1500);
const ask = (p, op) => p.evaluate(op => new Promise(res => window.__game.net.sendOp(op, res)), op);
const nMach = p => p.evaluate(() => window.__game.factory.machines.length);
const out = {};
out.place1 = await ask(B, { k: 'place', kind: 'storage', x: 5, y: 0, z: 5, yaw: 0, ore: null });
out.place2 = await ask(B, { k: 'place', kind: 'smelter', x: 9, y: 0, z: 5, yaw: 0, ore: null });
await A.evaluate(() => { const g = window.__game, m = g.factory.addMachine('constructor', 12, 0, 5, 0); g.factoryView.addMachine(m); g.planetRef().addMachineCollider(m.id, 12, 0, 5); });
await A.waitForTimeout(2500);
out.machinesAB = [await nMach(A), await nMach(B)];
out.link = await ask(B, { k: 'link', from: 2, to: 3 });
await A.waitForTimeout(1500);
out.linksAB = [await A.evaluate(() => window.__game.factory.links.length), await B.evaluate(() => window.__game.factory.links.length)];
out.build = await ask(B, { k: 'build', p: { type: 'foundation', cx: 3, cz: 3, level: 1, edge: 0, axis: 0, color: 0x8f95a3 } });
await A.evaluate(() => window.__game.buildSystem.add({ type: 'foundation', cx: 4, cz: 3, level: 1, edge: 0, axis: 0, color: 0xc0553a }));
await A.waitForTimeout(2000);
out.piecesAB = [await A.evaluate(() => window.__game.buildSystem.pieces.length), await B.evaluate(() => window.__game.buildSystem.pieces.length)];
out.dup = await ask(B, { k: 'build', p: { type: 'foundation', cx: 3, cz: 3, level: 1, edge: 0, axis: 0, color: 1 } });
out.remove = await ask(B, { k: 'remove', id: 2 });
await A.waitForTimeout(2000);
out.afterRemoveAB = [await nMach(A), await nMach(B)];
await A.evaluate(() => window.__game.net.sendWorld('hub', 0, [-12, -12, 0, 0]));
await B.waitForTimeout(1500);
out.hubOnB = await B.evaluate(() => !!window.__game.planetRef().hub);
console.log(JSON.stringify(out, null, 1), A.errs, B.errs);
await b.close();
